import type { Metadata } from 'next'
import { notFound } from 'next/navigation'
import { Brand } from '@/components/Brand'
import { PlayButton } from '@/components/PlayButton'
import { PostcardActions } from '@/components/PostcardActions'
import { PostcardImage } from '@/components/PostcardImage'
import { SimilarList } from '@/components/SimilarList'
import { Tags } from '@/components/Tags'
import { ApiError } from '@/lib/api'
import { formatDate, formatHour, percent, placeLine, timeWord } from '@/lib/format'
import { serverApi } from '@/lib/server'
import type { Postcard } from '@/lib/types'

export const dynamic = 'force-dynamic'

async function load(id: string): Promise<Postcard> {
  try {
    return await serverApi().postcard(id)
  } catch (error) {
    if (error instanceof ApiError && error.status === 404) notFound()
    throw error
  }
}

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }): Promise<Metadata> {
  const { id } = await params
  try {
    const card = await serverApi().postcard(id)
    const title = `Sounds of ${placeLine(card)}`
    const description = `Ten seconds of ${card.tags.map((tag) => tag.name.toLowerCase()).join(', ')}, recorded ${formatDate(card.local_date)}.`
    return {
      title,
      description,
      openGraph: { title, description, type: 'article', images: [{ url: card.image_url, width: 1200, height: 840 }] },
      twitter: { card: 'summary_large_image', title, description, images: [card.image_url] },
    }
  } catch {
    return { title: 'Postcard' }
  }
}

export default async function PostcardPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params
  const card = await load(id)
  const width = Math.round(card.cell.width_m / 10) * 10
  return (
    <main className="page page--wide">
      <header className="page__header">
        <Brand />
      </header>
      <div className="detail">
        <div>
          <PostcardImage card={card} size="full" eager />
          <div className="detail__head">
            <PlayButton src={card.audio_url} label={`ten seconds from ${card.place_name}`} />
            <div style={{ minWidth: 0 }}>
              <h1 className="detail__place">{placeLine(card)}</h1>
              <p className="note" style={{ fontSize: 14.5, marginBottom: 8 }}>
                {formatDate(card.local_date)}, around {formatHour(card.local_hour)}
              </p>
              <Tags card={card} />
            </div>
          </div>
          <PostcardActions card={card} />
        </div>

        <div>
          <SimilarList card={card} />

          <h2 className="section-title">What the model heard</h2>
          <div className="card heard">
            {card.labels.slice(0, 6).map((label) => (
              <div key={label.name} className="heard__row">
                <span>{label.name}</span>
                <div className="heard__bar">
                  <i style={{ width: percent(Math.min(1, label.score)) }} />
                </div>
                <em>{percent(label.score)}</em>
              </div>
            ))}
            <p className="note" style={{ marginTop: 4 }}>
              Labels from YAMNet, a 521-class audio tagger. Speech made up {percent(card.speech_probability)} of this clip; anything over 60% is
              refused.
            </p>
          </div>

          <h2 className="section-title">About this pin</h2>
          <dl className="card facts">
            <div>
              <dt>Where</dt>
              <dd>
                {Math.abs(card.lat).toFixed(3)}°{card.lat >= 0 ? 'N' : 'S'}, {Math.abs(card.lon).toFixed(3)}°{card.lon >= 0 ? 'E' : 'W'}
              </dd>
            </div>
            <div>
              <dt>Precision</dt>
              <dd>A square about {width} m wide</dd>
            </div>
            <div>
              <dt>When</dt>
              <dd>
                {timeWord(card.time_of_day)}, {formatDate(card.local_date)}
              </dd>
            </div>
            {card.weather?.condition && (
              <div>
                <dt>Weather</dt>
                <dd style={{ textTransform: 'capitalize' }}>{card.weather.condition}</dd>
              </div>
            )}
            <div>
              <dt>Picture</dt>
              <dd>{card.image_provider === 'procedural' ? 'Painted by the built-in painter' : `Generated by ${card.image_provider}`}</dd>
            </div>
            {card.seeded && (
              <div>
                <dt>Source</dt>
                <dd>Sample postcard with a synthetic sound</dd>
              </div>
            )}
          </dl>
        </div>
      </div>
    </main>
  )
}
